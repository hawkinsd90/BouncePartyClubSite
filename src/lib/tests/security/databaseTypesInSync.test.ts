// src/lib/database.types.ts is GENERATED (scripts/dev/gen-db-types.cjs) from the replayed repository migration chain. This test regenerates
// it from the scratch database bpc_replay_full and fails when the committed file differs, so a migration can never again change the schema
// without the application types following. It needs the pipeline scratch server (see scripts/dev/PIPELINE.md); without it the layer is
// reported as SKIPPED (it did NOT run), never as passed.
declare const require: (id: string) => any; // eslint-disable-line @typescript-eslint/no-explicit-any
declare const process: { env: Record<string, string | undefined>; argv: string[] };
const fs = require('fs');
const { spawnSync } = require('child_process');

let passed = 0;
let failed = 0;
let skipped = 0;
function ok(label: string, cond: boolean) {
  if (cond) passed++;
  else {
    failed++;
    console.error(`FAIL ${label}`);
  }
}

const committed: string = fs.readFileSync('src/lib/database.types.ts', 'utf8').replace(/\r\n/g, '\n');
ok('the committed file says it is generated and how to regenerate it', /Generated by scripts\/dev\/gen-db-types\.cjs/.test(committed) && /gen-db-types\.cjs --db bpc_replay_full/.test(committed));
ok('the exports the application relies on are present (Json, Database)', /export type Json =/.test(committed) && /export type Database = \{/.test(committed));
ok('no hand-written derived Insert helpers remain (Insert types come from the schema)', !/Omit<Database\['public'\]\['Tables'\]/.test(committed));

const out = `${process.env.TEMP || process.env.TMPDIR || '.'}/database.types.regenerated.${Date.now()}.ts`;
const run = spawnSync(process.execPath, ['scripts/dev/gen-db-types.cjs', '--db', 'bpc_replay_full', '--out', out], { encoding: 'utf8', env: { ...process.env, PGPORT: process.env.PGPORT || '54339' } });
if (run.status !== 0) {
  skipped++;
  console.log(`SKIPPED: the scratch database bpc_replay_full is not reachable (${String(run.stderr).split('\n')[0].slice(0, 120)}); the regeneration comparison did NOT run`);
} else {
  const fresh: string = fs.readFileSync(out, 'utf8').replace(/\r\n/g, '\n');
  fs.unlinkSync(out);
  ok('database.types.ts equals a fresh generation from bpc_replay_full (run: node scripts/dev/gen-db-types.cjs --db bpc_replay_full --out src/lib/database.types.ts)', fresh === committed);
}

console.log(`database types in sync: ${passed} passed, ${failed} failed, ${skipped} skipped`);
if (failed > 0) throw new Error(`${failed} database types test(s) failed`);
