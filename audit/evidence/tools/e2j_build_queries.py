"""Stage E2J: derive the hosted-ready read-only query package (e2j-development-readonly-queries.sql) from the reviewed E2I plan.
Offline text transformation only: no database connection. Each query becomes a tagged block (`-- @query Qnn <n>`), one statement per tag index, so that outputs map deterministically to query ids.
Usage: python -I e2j_build_queries.py"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EV = os.path.abspath(os.path.join(HERE, ".."))
src = open(os.path.join(EV, "e2i-development-readonly-evidence-plan.sql"), encoding="utf-8").read()
priv = json.load(open(r"C:\Users\vikki\migration-evidence\e2j-privobj.json"))
REL = sorted(r["name"] for r in priv["rels"])
FNS = sorted(priv["fns"])

parts = re.split(r"(?m)^-- (Q\d\d)  ", src)
queries = {}
for i in range(1, len(parts), 2):
    q, body = parts[i], parts[i + 1]
    body = "\n".join(body.split("\n")[1:])  # drop the remainder of the title line
    sql = "\n".join(l for l in body.split("\n") if not l.lstrip().startswith("--"))
    queries[q] = [s.strip() for s in sql.split(";") if s.strip()]

# --- reviewed modifications (see e2j-readonly-query-review.csv, column modification_before_hosted_use) ---
queries["Q11"][0] = """SELECT count(*) AS orders_total,
       count(*) FILTER (WHERE balance_due_cents IS NULL) AS balance_due_null,
       count(*) FILTER (WHERE tax_waived IS NULL) AS tax_waived_null,
       count(*) FILTER (WHERE tax_waived IS TRUE AND COALESCE(tax_cents,0) > 0) AS tax_waived_with_tax,
       count(*) FILTER (WHERE customer_selected_payment_cents IS NULL AND deposit_due_cents IS NOT NULL) AS selected_payment_unset
FROM orders"""
queries["Q23"][0] = queries["Q23"][0].replace(
    "md5(replace(p.prosrc, E'\\r', '')) AS body_md5_no_cr,",
    "md5(replace(p.prosrc, E'\\r', '')) AS body_md5_no_cr,\n       md5(regexp_replace(regexp_replace(replace(p.prosrc, E'\\r', ''), E'--[^\\n]*', '', 'g'), E'\\\\s+', '', 'g')) AS body_md5_no_comment_no_space,")
assert "no_comment_no_space" in queries["Q23"][0]
quoted_rel = ",".join("'%s'" % r for r in REL)
quoted_fn = ",".join("'%s'" % f for f in FNS)
queries["Q30"] = [
    f"""SELECT c.relname, c.relkind, c.relrowsecurity AS rls_enabled, pg_get_userbyid(c.relowner) AS owner, coalesce(c.relacl::text, '') AS acl
FROM pg_class c
WHERE c.relnamespace = 'public'::regnamespace AND c.relname IN ({quoted_rel})
ORDER BY c.relname""",
    f"""SELECT p.proname, (p.prorettype = 'trigger'::regtype) AS is_trigger_function, p.prosecdef AS security_definer, coalesce(p.proacl::text, '') AS acl
FROM pg_proc p
WHERE p.pronamespace = 'public'::regnamespace AND p.proname IN ({quoted_fn})
ORDER BY p.proname, p.oid""",
    """SELECT t.tbl,
       has_table_privilege('service_role', 'public.' || t.tbl, 'SELECT') AS service_role_select,
       has_table_privilege('service_role', 'public.' || t.tbl, 'INSERT') AS service_role_insert,
       has_table_privilege('anon', 'public.' || t.tbl, 'SELECT') AS anon_select,
       has_table_privilege('authenticated', 'public.' || t.tbl, 'SELECT') AS authenticated_select
FROM unnest(ARRAY['inventory_products','product_pricing','product_categories','product_bundles','product_bundle_components','package_inflatable_components','package_inflatable_eligibility','product_bundle_excluded_categories','contact_inquiries','order_portal_links','public_menu_groups','public_menu_group_categories']) AS t(tbl)
ORDER BY t.tbl""",
    f"""SELECT tablename, policyname, cmd, roles
FROM pg_policies
WHERE schemaname = 'public' AND tablename IN ({quoted_rel})
ORDER BY tablename, policyname""",
]

queries["Q00"] = [
    """SELECT current_database() AS database_name, current_user AS session_role,
       (SELECT rolsuper FROM pg_roles WHERE rolname = current_user) AS is_superuser,
       (SELECT rolbypassrls FROM pg_roles WHERE rolname = current_user) AS bypasses_rls,
       current_setting('default_transaction_read_only') AS default_read_only,
       current_setting('transaction_read_only') AS transaction_read_only,
       pg_has_role(current_user, 'pg_read_all_data', 'member') AS member_of_pg_read_all_data,
       has_table_privilege(current_user, 'public.orders', 'INSERT') AS can_insert_orders,
       current_setting('statement_timeout') AS statement_timeout,
       current_setting('server_version') AS server_version,
       (now() AT TIME ZONE 'utc') AS captured_at_utc""",
    """SELECT n.nspname, c.relname, c.relrowsecurity AS rls_enabled, c.relforcerowsecurity AS rls_forced, c.reltuples::bigint AS estimated_rows
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ('r','p') AND n.nspname IN ('public','auth','storage','supabase_migrations')
ORDER BY 1, 2""",
]
order = sorted(queries, key=lambda x: int(x[1:]))
out = ["""-- =====================================================================================================================
-- E2J: hosted-ready READ-ONLY query package for the DEVELOPMENT project (generated by tools/e2j_build_queries.py from the reviewed E2I plan).
-- STATUS: NOT RUN against any hosted system. Do not run without the owner's separate written approval (e2j-development-capture-authorization.md).
-- Format: every statement is preceded by a tag line `-- @query Qnn <index>`; run exactly one statement at a time, save its output under that tag.
-- Every statement is a single SELECT without a locking clause; the only functions called are the read-only catalog/accessor functions listed in
-- e2j-readonly-query-review.csv. Purpose, versions, minimum privileges and verdict effect for each query are in that CSV and in
-- e2i-development-readonly-evidence-plan.sql (unchanged). Q11 and Q23 differ from the E2I text; Q30 is new.
-- =====================================================================================================================
"""]
for q in order:
    for n, s in enumerate(queries[q], 1):
        out.append(f"-- @query {q} {n}\n{s};\n")
open(os.path.join(EV, "e2j-development-readonly-queries.sql"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(len(order), "queries,", sum(len(v) for v in queries.values()), "statements")
